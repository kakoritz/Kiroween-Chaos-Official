// `npm run bot:new -- <haunt.yaml>` (chain-wizard-v2 R3): a runnable, deliberately naive bot for ANY app, with the app's own stage ids and effects.
// It is the own-bot template (templates/own-bot) with its stage table replaced, so it speaks the same event protocol and chaos breaks it the same way.
// Node only (reads the template files).
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { HauntConfig } from '../config/haunt-config';

export type BotLang = 'node' | 'python';

/** Provider endpoint per effect kind (the fake provider's kinds). Any other kind goes to `/effects/<kind>` and is recorded under that name (contract v1.4). */
export const KIND_PATH: Readonly<Record<string, string>> = {
  account_create: '/accounts', account: '/accounts', order: '/orders', charge: '/charges', email: '/emails', store: '/store', dispatch: '/shipments',
  notify: '/notifications', ticket: '/tickets', reply: '/replies', refund: '/refunds', discount: '/discounts',
};
const HARDEN: Record<string, string> = {
  charge: 'a repeat is a double charge', refund: 'a repeat refunds twice', ticket: 'a repeat is a duplicate ticket', email: 'a repeat sends the mail twice',
  notify: 'a repeat notifies twice', dispatch: 'a repeat dispatches twice', order: 'a repeat places the order twice', account_create: 'a repeat creates the account twice', store: 'a repeat writes the row twice',
};

export interface StarterCall { path: string; body: Record<string, unknown>; kind: string }
export interface StarterStage { id: string; role: string; calls: StarterCall[] }

/** The stage table of a manifest: each effect becomes one provider call; the index counts each kind across the order, as the provider counts repeats. */
export function starterStages(config: HauntConfig): StarterStage[] {
  const used = new Map<string, number>();
  return config.stages.map((s) => ({
    id: s.id,
    role: s.role,
    calls: s.effects.map((e) => {
      const path = KIND_PATH[e.kind] ?? `/effects/${e.kind}`;
      const n = (used.get(path) ?? 0) + 1;
      used.set(path, n);
      return { path, kind: e.kind, body: { index: n } };
    }),
  }));
}

const js = (v: unknown): string => JSON.stringify(v);
const py = (v: unknown): string => JSON.stringify(v).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False').replace(/\bnull\b/g, 'None');

function nodeTable(stages: StarterStage[], name: string): string {
  const rows = stages.map((s) => {
    const note = s.calls.map((c) => `  // HARDEN (idempotency): send a key on the ${c.kind} call; ${HARDEN[c.kind] ?? 'a repeat is a bug'}.`).join('\n');
    return `${note ? note + '\n' : ''}  { id: ${js(s.id)}, calls: ${js(s.calls.map((c) => ({ path: c.path, body: c.body })))} },`;
  });
  return `// The stages of ${name}, from its haunt.yaml (generated by npm run bot:new). \`calls\` are the provider calls a stage makes; a stage with none is pure work.\nconst STAGES = [\n${rows.join('\n')}\n];`;
}

function pyTable(stages: StarterStage[], name: string): string {
  const rows = stages.map((s) => {
    const note = s.calls.map((c) => `    # HARDEN (idempotency): send a key on the ${c.kind} call; ${HARDEN[c.kind] ?? 'a repeat is a bug'}.`).join('\n');
    return `${note ? note + '\n' : ''}    {"id": ${js(s.id)}, "calls": ${py(s.calls.map((c) => ({ path: c.path, body: c.body })))}},`;
  });
  return `# The stages of ${name}, from its haunt.yaml (generated by npm run bot:new). \`calls\` are the provider calls a stage makes; a stage with none is pure work.\nSTAGES = [\n${rows.join('\n')}\n]`;
}

/** The bot source for `config` in `lang`. `root` is the repository root (where templates/own-bot lives). */
export function botStarter(config: HauntConfig, lang: BotLang, root = process.cwd()): string {
  const stages = starterStages(config);
  if (lang === 'node') {
    let t = readFileSync(resolve(root, 'templates/own-bot/bot.mjs'), 'utf8');
    const a = t.indexOf('// The stages of this bot.');
    const b = t.indexOf('];', a) + 2;
    if (a < 0 || b < 2) throw new Error('templates/own-bot/bot.mjs has no stage table to replace');
    t = t.slice(0, a) + nodeTable(stages, config.name) + t.slice(b);
    t = t.replace("if (stage.path) await callProvider(stage.path, { lane, order, ...stage.body }, null);", "for (const c of stage.calls) await callProvider(c.path, { lane, order, ...c.body }, null);");
    t = t.replace(/^\/\/ Own-bot template[^\n]*\n/, `// Bot starter for ${config.name} (generated by npm run bot:new). Run: npm run own-bot -- <this file> --app <folder of haunt.yaml>\n`);
    return t;
  }
  let t = readFileSync(resolve(root, 'templates/own-bot/bot.py'), 'utf8');
  const a = t.indexOf("# The arena's Stream app has these five stage ids");
  const b = t.indexOf(']\n', a) + 2;
  if (a < 0 || b < 2) throw new Error('templates/own-bot/bot.py has no stage table to replace');
  t = t.slice(0, a) + pyTable(stages, config.name) + '\n' + t.slice(b);
  t = t.replace('        if stage["path"]:\n            call_provider(stage["path"], {"lane": lane, "order": order, **stage["body"]}, None)', '        for c in stage["calls"]:\n            call_provider(c["path"], {"lane": lane, "order": order, **c["body"]}, None)');
  t = t.replace(/^# Own-bot template[^\n]*\n/, `# Bot starter for ${config.name} (generated by npm run bot:new). Run: npm run own-bot -- <this file> --app <folder of haunt.yaml>\n`);
  return t;
}
