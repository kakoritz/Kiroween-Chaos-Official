import { client } from './lib/haunt-client.mjs';
const c = client('http://127.0.0.1:7171');
await new Promise(r=>setTimeout(r,300));
const night = Number(process.argv[2]); const parts = (process.argv[3]||'').split(',').filter(Boolean);
const speed = Number(process.argv[4]||4);
const from = c.events.length;
const t0=Date.now();
const r = await c.post('/api/wave/start', { campaign: { night, parts }, speed });
console.log(JSON.stringify(r));
const end = await c.waitFor(e=>e.type==='wave_end', 300000, from);
console.log('secs', (Date.now()-t0)/1000);
console.log(JSON.stringify(end.detail?.summary ?? end).slice(0,3000));
const evs = c.events.slice(from);
const count = {}; for (const e of evs) count[e.type]=(count[e.type]||0)+1; console.log(JSON.stringify(count));
c.close(); process.exit(0);
